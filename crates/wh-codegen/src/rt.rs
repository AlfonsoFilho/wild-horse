//! `wh_rt`: the small runtime support module emitted into every generated crate.

pub const WH_RT: &str = r#"//! Runtime support for code generated by Wild Horse. Do not edit.
#![allow(dead_code)]

use std::fmt;

/// A value that does not satisfy a refinement, invariant or contract.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InvalidValue {
    pub node: &'static str,
    pub rule: &'static str,
    pub value: String,
}

impl InvalidValue {
    pub fn new(node: &'static str, rule: &'static str, value: String) -> Self {
        tracing::warn!(wh.node = node, rule, value = %value, "invalid value");
        Self { node, rule, value }
    }
}

impl fmt::Display for InvalidValue {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{} does not satisfy `{}` for {}", self.value, self.rule, self.node)
    }
}

impl std::error::Error for InvalidValue {}

/// Report a violated contract: logged at `error`, then panics (debug builds).
#[track_caller]
#[cold]
pub fn contract_violation(node: &'static str, kind: &'static str, source: &'static str) -> ! {
    tracing::error!(wh.node = node, contract = kind, source, "contract violated");
    panic!("wh: {kind} violated in {node}: `{source}`");
}

/// Entries a `Memoize` cache holds before it is cleared.
pub const MEMO_CAPACITY: usize = 4096;

/// One row of a state machine's transition table (`_` matches anything).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Transition {
    pub id: &'static str,
    pub from: &'static str,
    pub event: &'static str,
    pub to: &'static str,
    pub guard: Option<&'static str>,
    pub emit: Option<&'static str>,
}

impl Transition {
    /// Does this row apply to a `(state, event)` pair?
    pub fn matches(&self, state: &str, event: &str) -> bool {
        (self.from == "_" || self.from == state) && (self.event == "_" || self.event == event)
    }
}

/// Redacted stand-in printed for `sensitive` fields.
pub struct Redacted;

impl fmt::Debug for Redacted {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("<redacted>")
    }
}

/// Compile a regular expression once per call site.
#[macro_export]
macro_rules! wh_regex {
    ($re:expr) => {{
        static RE: std::sync::OnceLock<regex::Regex> = std::sync::OnceLock::new();
        RE.get_or_init(|| regex::Regex::new($re).expect("valid regular expression"))
    }};
}

/// Install the tracing subscriber for an application.
///
/// `WH_LOG` (or `RUST_LOG`) overrides `default_level`; `WH_TRACE_FILE`
/// additionally writes JSON events there (used by the Wild Horse IDE to map
/// events back to graph nodes).
pub fn init_tracing(default_level: &str, format: &str) {
    use tracing_subscriber::prelude::*;
    use tracing_subscriber::{EnvFilter, fmt};

    let filter = EnvFilter::try_from_env("WH_LOG")
        .or_else(|_| EnvFilter::try_from_default_env())
        .unwrap_or_else(|_| EnvFilter::new(default_level));
    // span closes (with their timings) make the execution path readable;
    // `WH_SPAN_EVENTS=off` keeps only events
    let span_events = if std::env::var("WH_SPAN_EVENTS").is_ok_and(|v| v == "off") {
        fmt::format::FmtSpan::NONE
    } else {
        fmt::format::FmtSpan::CLOSE
    };
    let console = match format {
        "json" => fmt::layer().json().with_span_events(span_events).with_writer(std::io::stderr).boxed(),
        "compact" => fmt::layer().compact().with_span_events(span_events).with_writer(std::io::stderr).boxed(),
        _ => fmt::layer().pretty().with_span_events(span_events).with_writer(std::io::stderr).boxed(),
    };
    let file_layer = std::env::var("WH_TRACE_FILE").ok().and_then(|path| {
        let file = std::fs::OpenOptions::new().create(true).append(true).open(path).ok()?;
        Some(
            fmt::layer()
                .json()
                .with_span_list(true)
                .with_span_events(fmt::format::FmtSpan::CLOSE)
                .with_writer(std::sync::Mutex::new(file))
                .with_filter(EnvFilter::new("trace")),
        )
    });
    let _ = tracing_subscriber::registry().with(console.with_filter(filter)).with(file_layer).try_init();
}

/// Install a subscriber that prints into the test harness's captured output.
pub fn init_test_tracing() {
    let _ = tracing_subscriber::fmt()
        .with_test_writer()
        .with_span_events(tracing_subscriber::fmt::format::FmtSpan::CLOSE)
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_env("WH_LOG")
                .unwrap_or_else(|_| tracing_subscriber::EnvFilter::new("debug")),
        )
        .try_init();
}
"#;
