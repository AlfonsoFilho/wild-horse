//! Generation of the bench crate: a sibling of the generated library with
//! one criterion benchmark group per hole, a counting global allocator and
//! deterministic input generators for the size sweep.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::Result;
use serde::{Deserialize, Serialize};
use wh_codegen::expr::{ExprGen, Scope};
use wh_codegen::rust::{Names, module_ident};
use wh_model::{Model, NodeKind, Ty};
use wh_syntax::ast::{ExprKind, ParamMode};

use crate::inputs::{InputGen, is_sized};
use crate::spec::PerfSpec;

/// Name of the auto-benchmark (benches from `bench` clauses use their own name).
pub const AUTO: &str = "auto";

/// Where and how to generate a bench crate.
#[derive(Debug, Clone)]
pub struct BenchCrateOptions {
    /// Directory of the bench crate (`<project>/.wh/bench`).
    pub dir: PathBuf,
    /// Cargo package name; unique among packages sharing a target dir.
    pub package: String,
    /// Directory of the generated library crate (`<project>/.wh/gen`).
    pub lib_dir: PathBuf,
    /// Package name of the generated library.
    pub lib_package: String,
    /// Rust crate name of the generated library (`signup`).
    pub lib: String,
    /// Only these nodes (all benchable holes when `None`).
    pub nodes: Option<Vec<String>>,
}

/// One benchmarked node.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BenchTarget {
    pub node: String,
    /// criterion benchmark names (`auto` and `bench` clause names).
    pub benches: Vec<String>,
    /// The auto-bench sweeps the input size (else it runs at one fixed size).
    pub sized: bool,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct Skipped {
    pub node: String,
    pub reason: String,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct BenchCrate {
    pub dir: PathBuf,
    pub package: String,
    pub targets: Vec<BenchTarget>,
    pub skipped: Vec<Skipped>,
}

/// The criterion group name of a node.
pub fn group_name(node: &str) -> String {
    node.to_string()
}

fn slug(node: &str) -> String {
    node.chars().map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_lowercase() } else { '_' }).collect()
}

/// Generate (or update) the bench crate; files are written only when their
/// content changed, so cargo's incremental cache stays warm.
pub fn generate_bench_crate(model: &Model, opts: &BenchCrateOptions) -> Result<BenchCrate> {
    let mut targets = Vec::new();
    let mut skipped = Vec::new();
    let mut fns = String::new();
    let mut calls = String::new();
    let ids: Vec<String> = match &opts.nodes {
        Some(n) => n.clone(),
        None => model.nodes.values().filter(|n| n.is_hole()).map(|n| n.id.clone()).collect(),
    };
    for id in ids {
        match bench_fn(model, &opts.lib, &id) {
            Ok((code, target)) => {
                fns.push_str(&code);
                let _ = writeln!(calls, "    if wh_perf_support::selected({id:?}) {{\n        bench_{}(&mut c);\n    }}", slug(&id));
                targets.push(target);
            }
            Err(reason) => skipped.push(Skipped { node: id, reason }),
        }
    }
    let bench = format!(
        "//! Generated by Wild Horse (wh-perf). Do not edit.\n#![allow(unused_imports, unused_variables, unused_mut, unused_parens, non_snake_case, clippy::all)]\n\nuse criterion::{{BatchSize, BenchmarkId, Criterion}};\nuse proptest::prelude::*;\nuse std::hint::black_box;\n\n{fns}fn main() {{\n    let mut c = Criterion::default().configure_from_args();\n{calls}    c.final_summary();\n}}\n"
    );
    let cargo = format!(
        "# Generated by Wild Horse (wh-perf). Do not edit.\n[package]\nname = {:?}\nversion = \"0.1.0\"\nedition = \"2024\"\npublish = false\nautobins = false\nautoexamples = false\nautotests = false\nautobenches = false\n\n[lib]\nname = \"wh_perf_support\"\npath = \"src/lib.rs\"\n\n[[bench]]\nname = \"wh_bench\"\npath = \"benches/wh_bench.rs\"\nharness = false\n\n[workspace]\n\n[dependencies]\n{} = {{ package = {:?}, path = {:?} }}\nproptest = \"1\"\n\n[dev-dependencies]\ncriterion = {{ version = \"0.8\", default-features = false }}\n\n[profile.release]\nopt-level = 3\ndebug = false\nincremental = true\n",
        opts.package,
        opts.lib,
        opts.lib_package,
        opts.lib_dir.to_string_lossy(),
    );
    write_if_changed(&opts.dir.join("Cargo.toml"), &cargo)?;
    write_if_changed(&opts.dir.join("src/lib.rs"), SUPPORT)?;
    write_if_changed(&opts.dir.join("benches/wh_bench.rs"), &bench)?;
    write_if_changed(&opts.dir.join(".gitignore"), "*\n")?;
    Ok(BenchCrate { dir: opts.dir.clone(), package: opts.package.clone(), targets, skipped })
}

fn write_if_changed(path: &Path, content: &str) -> std::io::Result<()> {
    if std::fs::read_to_string(path).ok().as_deref() == Some(content) {
        return Ok(());
    }
    if let Some(d) = path.parent() {
        std::fs::create_dir_all(d)?;
    }
    std::fs::write(path, content)
}

/// How the call passes a value: by reference, by copy, moved, or `&mut`.
fn arg(var: &str, mode: &ParamMode, copy: bool, black_box: bool) -> String {
    let e = match mode {
        ParamMode::Own => var.to_string(),
        ParamMode::Mut => format!("&mut {var}"),
        ParamMode::Borrow if copy => var.to_string(),
        ParamMode::Borrow => format!("&{var}"),
    };
    if black_box { format!("black_box({e})") } else { e }
}

/// The benchmark function of one node, or why it cannot be benchmarked.
fn bench_fn(model: &Model, lib: &str, id: &str) -> Result<(String, BenchTarget), String> {
    let node = model.nodes.get(id).ok_or("unknown node")?;
    let NodeKind::Def(info) = &node.kind else { return Err("only defs are benchmarked".into()) };
    if info.extern_path.is_some() {
        return Err("extern defs are not holes".into());
    }
    if node.def().is_some_and(|d| !d.sig.generics.is_empty()) {
        return Err("generic defs are not benchmarked yet".into());
    }
    if !info.sig.uses.is_empty() {
        return Err("defs that use capabilities are not benchmarked yet".into());
    }
    let spec = PerfSpec::of(model, id).ok_or("not a def")?;
    let names = Names::new(model, &node.module);
    let mut ig = InputGen::new(model, lib);
    let path = ig.path(id);
    let wrap = |call: String| if info.sig.is_async { format!("{lib}::wh_rt::block_on({call})") } else { call };
    let required: Vec<String> = spec.required_sizes().iter().map(|s| format!("{s}usize")).collect();
    let mut body = String::new();
    let group = group_name(id);
    let _ = writeln!(body, "fn bench_{}(c: &mut Criterion) {{\n    use {lib}::{}::*;\n    let mut g = c.benchmark_group({group:?});", slug(id), module_ident(&node.module));

    // auto-bench over the size sweep
    let params = &info.sig.params;
    let any_sized = params.iter().any(|p| is_sized(model, &p.ty));
    let any_int = params.iter().any(|p| matches!(p.ty, Ty::Int(_)));
    let sized = any_sized || any_int;
    let mut draws = String::new();
    for (k, p) in params.iter().enumerate() {
        let s = if any_sized { is_sized(model, &p.ty) } else { matches!(p.ty, Ty::Int(_)) };
        let strat = ig.strategy(&p.ty, s)?;
        let _ = writeln!(draws, "        let a{k} = wh_perf_support::draw(&mut rt, {strat});");
    }
    let batched = params.iter().any(|p| !matches!(p.mode, ParamMode::Borrow));
    let vars: Vec<String> = (0..params.len()).map(|k| format!("a{k}")).collect();
    let sizes = if sized { format!("wh_perf_support::sizes(&[{}])", required.join(", ")) } else { "vec![1usize]".into() };
    let _ = writeln!(body, "    for n in {sizes} {{\n        let mut rt = wh_perf_support::runner(n);\n{draws}");
    if batched {
        let call = wrap(format!(
            "{path}({})",
            params.iter().zip(&vars).map(|(p, v)| arg(v, &p.mode, names.is_copy(&p.ty), false)).collect::<Vec<_>>().join(", ")
        ));
        let tuple = format!("({},)", vars.join(", "));
        let pat = format!("({},)", vars.iter().map(|v| format!("mut {v}")).collect::<Vec<_>>().join(", "));
        let clone = format!("({},)", vars.iter().map(|v| format!("{v}.clone()")).collect::<Vec<_>>().join(", "));
        let _ = writeln!(
            body,
            "        let inp = {clone};\n        let (allocs, bytes) = wh_perf_support::count_allocs(move || {{\n            let {pat} = inp;\n            let r = {call};\n            (r, {tuple})\n        }});\n        wh_perf_support::record({id:?}, {AUTO:?}, n, allocs, bytes);\n        g.bench_with_input(BenchmarkId::new({AUTO:?}, n), &n, |b, _| {{\n            b.iter_batched(|| {clone}, |{pat}| {{\n                let r = {call};\n                (r, {tuple})\n            }}, BatchSize::SmallInput)\n        }});"
        );
    } else {
        let call = |bb: bool| {
            wrap(format!(
                "{path}({})",
                params.iter().zip(&vars).map(|(p, v)| arg(v, &p.mode, names.is_copy(&p.ty), bb)).collect::<Vec<_>>().join(", ")
            ))
        };
        let _ = writeln!(
            body,
            "        let (allocs, bytes) = wh_perf_support::count_allocs(|| {});\n        wh_perf_support::record({id:?}, {AUTO:?}, n, allocs, bytes);\n        g.bench_with_input(BenchmarkId::new({AUTO:?}, n), &n, |b, _| b.iter(|| {}));",
            call(false),
            call(true)
        );
    }
    body.push_str("    }\n");

    // `bench` clauses
    let mut benches = vec![AUTO.to_string()];
    for bc in &spec.benches {
        let eg = ExprGen::new(model, &node.module);
        let mut scope = Scope::default();
        let mut draws = String::new();
        let mut fixed: Option<String> = None;
        let mut swept = false;
        let bc_sized = bc.params.iter().any(|(_, t)| is_sized(model, t));
        for (p, ty) in &bc.params {
            let var = format!("p_{}", p.name.name);
            match (ty, &p.default) {
                (Ty::Int(i), Some(d)) => {
                    let v = match &d.kind {
                        ExprKind::Int(v) => v.replace('_', ""),
                        _ => return Err(format!("bench `{}`: the default of `{}` must be an integer literal", bc.name, p.name.name)),
                    };
                    fixed = Some(v.clone());
                    let _ = writeln!(draws, "        let {var}: {} = {v};", i.rust());
                }
                (Ty::Int(i), None) if !bc_sized => {
                    swept = true;
                    let _ = writeln!(draws, "        let {var}: {0} = {0}::try_from(n).unwrap_or({0}::MAX);", i.rust());
                }
                _ => {
                    let s = is_sized(model, ty);
                    swept |= s;
                    let strat = ig.strategy(ty, s).map_err(|e| format!("bench `{}`: {e}", bc.name))?;
                    let _ = writeln!(draws, "        let {var} = wh_perf_support::draw(&mut rt, {strat});");
                }
            }
            scope.var(&p.name.name, &var, ty.clone(), false);
        }
        let code = eg.emit(&bc.body, &scope).replace("crate::", &format!("{lib}::"));
        let sizes = match (&fixed, swept) {
            (_, true) => format!("wh_perf_support::sizes(&[{}])", required.join(", ")),
            (Some(v), false) => format!("vec![{v}usize]"),
            (None, false) => "vec![1usize]".into(),
        };
        let name = &bc.name;
        let _ = writeln!(
            body,
            "    for n in {sizes} {{\n        let mut rt = wh_perf_support::runner(n);\n{draws}        let (allocs, bytes) = wh_perf_support::count_allocs(|| {code});\n        wh_perf_support::record({id:?}, {name:?}, n, allocs, bytes);\n        g.bench_with_input(BenchmarkId::new({name:?}, n), &n, |b, _| b.iter(|| black_box({code})));\n    }}"
        );
        benches.push(bc.name.clone());
    }
    body.push_str("    g.finish();\n}\n\n");
    Ok((body, BenchTarget { node: id.to_string(), benches, sized }))
}

/// The bench crate's library: counting allocator, size sweep, input draws.
const SUPPORT: &str = r#"//! Generated by Wild Horse (wh-perf). Do not edit.
//!
//! Support code for the generated benchmarks: a counting global allocator
//! (allocations are only counted inside `count_allocs`), the input-size
//! sweep, and deterministic input generation.
#![allow(clippy::all)]

use std::alloc::{GlobalAlloc, Layout, System};
use std::io::Write as _;
use std::sync::atomic::{AtomicBool, AtomicU64, Ordering};

use proptest::strategy::{Strategy, ValueTree};
use proptest::test_runner::{Config, RngAlgorithm, TestRng, TestRunner};

pub struct Counting;

static ON: AtomicBool = AtomicBool::new(false);
static COUNT: AtomicU64 = AtomicU64::new(0);
static BYTES: AtomicU64 = AtomicU64::new(0);

fn note(bytes: usize) {
    if ON.load(Ordering::Relaxed) {
        COUNT.fetch_add(1, Ordering::Relaxed);
        BYTES.fetch_add(bytes as u64, Ordering::Relaxed);
    }
}

unsafe impl GlobalAlloc for Counting {
    unsafe fn alloc(&self, layout: Layout) -> *mut u8 {
        note(layout.size());
        unsafe { System.alloc(layout) }
    }

    unsafe fn alloc_zeroed(&self, layout: Layout) -> *mut u8 {
        note(layout.size());
        unsafe { System.alloc_zeroed(layout) }
    }

    unsafe fn dealloc(&self, ptr: *mut u8, layout: Layout) {
        unsafe { System.dealloc(ptr, layout) }
    }

    unsafe fn realloc(&self, ptr: *mut u8, layout: Layout, new_size: usize) -> *mut u8 {
        note(new_size.saturating_sub(layout.size()));
        unsafe { System.realloc(ptr, layout, new_size) }
    }
}

#[global_allocator]
static GLOBAL: Counting = Counting;

/// Heap allocations (count, bytes) made while running `f` once; dropping
/// the result is not counted.
pub fn count_allocs<R>(f: impl FnOnce() -> R) -> (u64, u64) {
    COUNT.store(0, Ordering::SeqCst);
    BYTES.store(0, Ordering::SeqCst);
    ON.store(true, Ordering::SeqCst);
    let r = std::hint::black_box(f());
    ON.store(false, Ordering::SeqCst);
    let out = (COUNT.load(Ordering::SeqCst), BYTES.load(Ordering::SeqCst));
    drop(r);
    out
}

/// Append one allocation measurement to `$WH_PERF_ALLOC_OUT`.
pub fn record(node: &str, bench: &str, size: usize, allocs: u64, bytes: u64) {
    let Some(path) = std::env::var_os("WH_PERF_ALLOC_OUT") else { return };
    if let Ok(mut f) = std::fs::OpenOptions::new().create(true).append(true).open(path) {
        let _ = writeln!(f, "{node}\t{bench}\t{size}\t{allocs}\t{bytes}");
    }
}

/// The size sweep: `$WH_PERF_SIZES` (comma separated) plus the sizes the
/// spec requires (budgets).
pub fn sizes(required: &[usize]) -> Vec<usize> {
    let env = std::env::var("WH_PERF_SIZES").unwrap_or_else(|_| "64,256,1024,4096".into());
    let mut s: Vec<usize> = env.split(',').filter_map(|x| x.trim().parse().ok()).collect();
    s.extend_from_slice(required);
    s.sort_unstable();
    s.dedup();
    s
}

/// Is this node selected by `$WH_PERF_ONLY` (comma separated node ids)?
pub fn selected(node: &str) -> bool {
    match std::env::var("WH_PERF_ONLY") {
        Ok(only) if !only.trim().is_empty() => only.split(',').any(|n| n.trim() == node),
        _ => true,
    }
}

/// A deterministic input generator for size `n`.
pub fn runner(n: usize) -> TestRunner {
    let mut seed = [0x5au8; 32];
    seed[..8].copy_from_slice(&(n as u64).to_le_bytes());
    TestRunner::new_with_rng(Config::default(), TestRng::from_seed(RngAlgorithm::ChaCha, &seed))
}

pub fn draw<S: Strategy>(runner: &mut TestRunner, strategy: S) -> S::Value {
    strategy.new_tree(runner).expect("generating a benchmark input").current()
}
"#;
